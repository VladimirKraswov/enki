// Bundle the runtime sources (including the shared Enki extension sources in
// ../shared, ../browser and ../pi) into dist/main.js. SDK and native packages
// stay external: they are installed from the reviewed lockfile next to dist/.
// Run only by scripts/runtime/prepare.mjs inside an isolated staging copy.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
// Outputs inside src-tauri would change the native compatibility fingerprint
// computed from the working tree; bundling happens only in staging copies.
if (root.split(path.sep).join("/").includes("/src-tauri/resources/agent")) {
  console.error("build.mjs must run in a staging copy (scripts/runtime/prepare.mjs), not in src-tauri/resources/agent.");
  process.exit(2);
}
const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const runtimePin = JSON.parse(readFileSync(path.join(root, "runtime-lock.json"), "utf8"));
// The ONE binding of each pin in this file. Every consumer below uses these
// names; scripts/runtime/sdk-contract.mjs audits the binding AND each consumer
// individually, so one hardcoded site cannot hide behind another reference.
const PINNED_SDK = runtimePin.sdk.version;
const PINNED_DATA_SCHEMA = runtimePin.dataSchema;
const PINNED_CONTRACT = runtimePin.contract;
if (process.version !== `v${runtimePin.node.version}`) throw new Error("Build must use the exact pinned runtime Node interpreter.");
const sdkPackages = ["pi-agent-core", "pi-ai", "pi-coding-agent", "pi-tui", "chord", "pi-telemetry"];
for (const name of sdkPackages) {
  const key = `@earendil-works/${name}`;
  const installed = JSON.parse(readFileSync(path.join(root, "node_modules", key, "package.json"), "utf8"));
  if (pkg.dependencies[key] !== PINNED_SDK || pkg.overrides?.[key] !== PINNED_SDK || installed.version !== PINNED_SDK) throw new Error(`Unqualified SDK dependency: ${key}`);
}
// The artifact metadata (runtime-version.json) is what the installer pairs
// backups and identities with; it must equal the constants the bundle speaks.
const protocol = readFileSync(path.join(root, "src/protocol.ts"), "utf8");
const constant = (name) => protocol.match(new RegExp(`^export const ${name} = ("?)([^";]+)\\1;\\r?$`, "m"))?.[2];
for (const [name, pinned] of [["CONTRACT_VERSION", PINNED_CONTRACT], ["SCHEMA_VERSION", PINNED_DATA_SCHEMA], ["SDK_VERSION", PINNED_SDK]])
  if (constant(name) !== String(pinned)) throw new Error(`runtime-lock.json ${name} ${pinned} does not match src/protocol.ts ${constant(name)}`);
const external = [...Object.keys(pkg.dependencies ?? {}), "@modelcontextprotocol/sdk/*", "@earendil-works/*", "node:*"];

await build({
  entryPoints: [path.join(root, "src/main.ts")],
  outfile: path.join(root, "dist/main.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24.22",
  sourcemap: "linked",
  external,
  nodePaths: [path.join(root, "node_modules")],
  banner: { js: "// Enki Runtime — generated by build.mjs; do not edit." },
  logLevel: "warning",
});
// Trusted remote updater may import this file only AFTER authenticating the
// candidate manifest. This entry contains no SDK/bootstrap or live runtime.
await build({ entryPoints: [path.join(root, "src/daemon-control.ts")], outfile: path.join(root, "dist/daemon-control.js"),
  bundle: true, platform: "node", format: "esm", target: "node24.22", sourcemap: "linked", external,
  nodePaths: [path.join(root, "node_modules")], logLevel: "warning" });

const lock = readFileSync(path.join(root, "package-lock.json"));
const runtimeLock = readFileSync(path.join(root, "runtime-lock.json"));
const bundle = readFileSync(path.join(root, "dist/main.js"));
const control = readFileSync(path.join(root, "dist/daemon-control.js"));
const id = createHash("sha256").update(runtimeLock).update(lock).update(bundle).update(control).digest("hex").slice(0, 16);
mkdirSync(path.join(root, "dist"), { recursive: true });
writeFileSync(path.join(root, "runtime-version.json"), JSON.stringify({ version: id, sdk: PINNED_SDK,
  node: runtimePin.node.version, contract: PINNED_CONTRACT, dataSchema: PINNED_DATA_SCHEMA,
  dependencyLockSha256: createHash("sha256").update(lock).digest("hex"),
  runtimeLockSha256: createHash("sha256").update(runtimeLock).digest("hex"),
  bundleSha256: createHash("sha256").update(bundle).digest("hex") }, null, 2));
console.log(id);
