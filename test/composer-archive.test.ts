// @vitest-environment jsdom
import 'fake-indexeddb/auto';
import { File as NodeFile, Blob as NodeBlob } from 'node:buffer';
import { act, createElement } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, expect, it, vi } from 'vitest';
vi.mock('../src/components/ContextMeter', () => ({ ContextMeter: () => null }));
vi.mock('../src/components/WorkspacePicker', () => ({ HostPicker: () => null }));
vi.mock('../src/components/VoiceInput', () => ({ VoiceInput: () => null }));
let root: Root | undefined;
afterEach(async () => { if (root) await act(async () => root!.unmount()); root = undefined; document.body.replaceChildren(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
async function setup() {
  vi.resetModules(); vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT', true);
  vi.stubGlobal('matchMedia', () => ({ matches: false, addEventListener() {}, removeEventListener() {} }));
  vi.stubGlobal('File', NodeFile); vi.stubGlobal('Blob', NodeBlob);
  const fixture = await import('./helpers/runtime-fixture');
  const { store } = await import('../src/state/store');
  const { Composer } = await import('../src/components/Composer');
  const { attachmentDrafts, attachmentScope } = await import('../src/attachments/drafts');
  const directory = '/archive-ui-' + crypto.randomUUID();
  const archive = { id: 'legacy-' + crypto.randomUUID(), directory, title: 'История', projectID: 'p', origin: { kind: 'opencode' }, time: { created: 1, updated: 1 } };
  const continued = { ...archive, id: 'continued-' + crypto.randomUUID(), origin: undefined };
  const other = { ...continued, id: 'other-' + crypto.randomUUID() };
  const fx = fixture.runtimeFixture(); fixture.withProvider(fx);
  fx.on('GET', '/sessions', () => [archive, continued, other]);
  fx.on('POST', '/sessions/:id/continue', () => continued);
  fixture.bindStore(store, fx);
  await store.setDirectory(directory, { sessionId: archive.id });
  store.setModelChoice('p', 'm', 'medium'); store.setDraft('Мой запрос');
  const scope = attachmentScope(store.state.prefs.workspaceKey!, directory, archive.id);
  await attachmentDrafts.add(scope, [new NodeFile(['evidence'], 'input.txt', { type: 'text/plain' }) as unknown as File]);
  const node = document.createElement('div'); document.body.append(node); root = createRoot(node);
  await act(async () => root!.render(createElement(Composer)));
  return { store, fx, directory, archive, continued, other, scope, attachmentDrafts, attachmentScope };
}
it('explains the archive before Send and continues with the latest draft and files without executing a prompt', async () => {
  const f = await setup();
  expect(document.body.textContent).toContain('Этот чат доступен только для чтения');
  const button = document.querySelector<HTMLButtonElement>('button[aria-label="Продолжить чат"]');
  expect(button).not.toBeNull();
  expect(document.querySelector<HTMLButtonElement>('button[aria-label="Send prompt"]')!.disabled).toBe(true);
  await act(async () => document.querySelector('textarea')!.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })));
  expect(f.fx.made('POST', '/commands')).toHaveLength(0);
  expect(f.fx.made('POST', '/sessions/:id/continue')).toHaveLength(0);
  let answer!: (value: unknown) => void;
  f.fx.on('POST', '/sessions/:id/continue', () => new Promise(resolve => { answer = resolve; }));
  await act(async () => button!.click());
  await vi.waitFor(() => expect(answer).toBeTypeOf('function'));
  const same = f.store.continueLegacySession(f.archive as never);
  await act(async () => f.store.setDraft('Последнее уточнение'));
  expect(document.querySelector<HTMLButtonElement>('button[aria-label="Продолжить чат"]')!.disabled).toBe(true);
  await act(async () => { answer(f.continued); await same; });
  expect(f.fx.made('POST', '/sessions/:id/continue')).toHaveLength(1);
  expect(f.store.state.activeSessionId).toBe(f.continued.id);
  expect(f.store.getDraft()).toBe('Последнее уточнение');
  expect(f.store.state.prefs.drafts[f.archive.id]).toBeUndefined();
  expect(f.store.getModelChoice()).toMatchObject({ providerID: 'p', modelID: 'm', variant: 'medium' });
  const target = f.attachmentScope(f.store.state.prefs.workspaceKey!, f.directory, f.continued.id);
  expect(f.attachmentDrafts.snapshot(target).map(x => x.name)).toEqual(['input.txt']);
  expect(f.attachmentDrafts.snapshot(f.scope)).toHaveLength(0);
  expect(f.fx.made('POST', '/commands')).toHaveLength(0);
  expect(document.body.textContent).not.toContain('Этот чат доступен только для чтения');
});
it('keeps the draft and files in the archive after a failed continuation', async () => {
  const f = await setup(); f.fx.on('POST', '/sessions/:id/continue', () => { throw new Error('fixture unavailable'); });
  await act(async () => { await f.store.continueLegacySession(f.archive as never); });
  expect(f.store.state.activeSessionId).toBe(f.archive.id); expect(f.store.getDraft()).toBe('Мой запрос');
  expect(f.attachmentDrafts.snapshot(f.scope)).toHaveLength(1);
  expect(document.querySelector<HTMLButtonElement>('button[aria-label="Продолжить чат"]')!.disabled).toBe(false);
  expect(f.fx.made('POST', '/commands')).toHaveLength(0);
});
it('does not pull the user back when continuation answers after another chat was opened', async () => {
  const f = await setup(); let answer!: (value: unknown) => void;
  f.fx.on('POST', '/sessions/:id/continue', () => new Promise(resolve => { answer = resolve; }));
  let pending!: Promise<boolean>;
  await act(async () => { pending = f.store.continueLegacySession(f.archive as never); });
  await vi.waitFor(() => expect(answer).toBeTypeOf('function'));
  await act(async () => { await f.store.selectSession(f.other.id); f.store.setDraft('Другой чат'); });
  await act(async () => { answer(f.continued); await pending; });
  expect(f.store.state.activeSessionId).toBe(f.other.id); expect(f.store.getDraft()).toBe('Другой чат');
  expect(f.fx.made('POST', '/commands')).toHaveLength(0);
});
it('keeps input intact after an attachment-store transfer failure and continues on retry', async () => {
  const f = await setup();
  const move = vi.spyOn(f.attachmentDrafts, 'move').mockRejectedValueOnce(new Error('IndexedDB unavailable'));
  await act(async () => { await f.store.continueLegacySession(f.archive as never); });
  expect(f.store.state.activeSessionId).toBe(f.archive.id);
  expect(f.store.getDraft()).toBe('Мой запрос');
  expect(f.attachmentDrafts.snapshot(f.scope)).toHaveLength(1);
  expect(document.body.textContent).toContain('Черновик сохранён');
  move.mockRestore();
  const button = document.querySelector<HTMLButtonElement>('button[aria-label="Продолжить чат"]')!;
  expect(button.disabled).toBe(false);
  await act(async () => { await f.store.continueLegacySession(f.archive as never); });
  expect(f.store.state.activeSessionId).toBe(f.continued.id);
  expect(f.store.getDraft()).toBe('Мой запрос');
  const target = f.attachmentScope(f.store.state.prefs.workspaceKey!, f.directory, f.continued.id);
  expect(f.attachmentDrafts.snapshot(target).map(x => x.name)).toEqual(['input.txt']);
  expect(f.fx.made('POST', '/commands')).toHaveLength(0);
});
it('appends the archive draft instead of overwriting the existing continuation draft', async () => {
  const f = await setup();
  f.store.state.prefs.drafts[f.continued.id] = 'Уже набрано в продолжении';
  await act(async () => { await f.store.continueLegacySession(f.archive as never); });
  expect(f.store.state.activeSessionId).toBe(f.continued.id);
  expect(f.store.getDraft()).toBe('Уже набрано в продолжении\n\nМой запрос');
  expect(f.store.state.prefs.drafts[f.archive.id]).toBeUndefined();
});
